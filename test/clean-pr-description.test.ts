// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { cleanBody } from '../scripts/clean-pr-description.mjs';

const credit = (tool: string, url: string): string => `_Generated by [${tool}](${url})_`;

describe('cleanBody', () => {
  it('removes a tool footer: the credit, a session link and the rule above them', () => {
    expect(cleanBody(`Adds a module.\n\n- One\n- Two\n\n---\n${credit('Some Tool', 'https://example.com/code/session_01ABC')}`)).toBe('Adds a module.\n\n- One\n- Two');
    expect(cleanBody(`Fix.\n\n\u{1F916} Generated with [Some Tool](https://example.com/tool)\n\nhttps://example.com/code/session_01ABC\n`)).toBe('Fix.');
    expect(cleanBody(`Fix.\n${credit('Tool', 'https://example.com')}`)).toBe('Fix.');
  });

  it('keeps descriptions without a footer exactly as they are', () => {
    for (const body of ['', 'Plain text.', 'Ends with a rule\n\n---', 'Mentions generated files\n\n- Generated by the build: dist/', '---\n\nStarts with a rule.']) {
      expect(cleanBody(body)).toBe(body);
    }
  });

  it('removes only the footer at the end, never a credit in the middle', () => {
    const body = `Intro.\n\n${credit('Tool', 'https://example.com')}\n\nMore text.`;
    expect(cleanBody(body)).toBe(body);
  });
});
